-- ==============================================================================
-- Script de création de la base et des tables (Oracle 19c/21c+)
-- Projet : Gestion des fonctionnalités, bilan annuel, rôles et habilitations
-- Version 2.0 : Hiérarchie, Intérims, Bilan enrichi
-- ==============================================================================

-- Note : En Oracle, les tables sont créées dans le schéma de l'utilisateur connecté
-- Pas de "CREATE DATABASE" ni "USE" comme en MySQL

-- =============================================================================
-- 1. STRUCTURE_ORGANISATIONNELLE (Pyramide hiérarchique 5 niveaux)
-- =============================================================================
BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE structure_organisationnelle CASCADE CONSTRAINTS';
EXCEPTION
  WHEN OTHERS THEN NULL;
END;
/

CREATE TABLE structure_organisationnelle (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR2(50)  NOT NULL UNIQUE,
    libelle         VARCHAR2(150) NOT NULL,
    niveau          VARCHAR2(20)  NOT NULL CHECK (niveau IN ('DIRECTION','DIVISION','SERVICE','SECTION')),
    parent_id       NUMBER(19),
    actif           NUMBER(1)     NOT NULL DEFAULT 1 CHECK (actif IN (0,1)),
    date_creation   TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    date_mise_a_jour TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_struct_parent FOREIGN KEY (parent_id) REFERENCES structure_organisationnelle (id) ON DELETE SET NULL
);

-- Trigger pour mise à jour automatique de date_mise_a_jour
CREATE OR REPLACE TRIGGER trg_struct_update
BEFORE UPDATE ON structure_organisationnelle
FOR EACH ROW
BEGIN
  :NEW.date_mise_a_jour := CURRENT_TIMESTAMP;
END;
/

-- =============================================================================
-- 2. UTILISATEUR (avec structure et rôles enrichis)
-- =============================================================================
BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE utilisateur CASCADE CONSTRAINTS';
EXCEPTION
  WHEN OTHERS THEN NULL;
END;
/

CREATE TABLE utilisateur (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR2(50)  NOT NULL UNIQUE,
    password        VARCHAR2(255) NOT NULL,
    nom_complet     VARCHAR2(150) NOT NULL,
    email           VARCHAR2(150),
    role            VARCHAR2(50)  NOT NULL CHECK (role IN (
        'ROLE_ADMIN',
        'ROLE_DIRECTION','ROLE_DIVISION','ROLE_SERVICE','ROLE_SECTION','ROLE_RESPONSABLE',
        'ROLE_OBSERVATEUR_GENERAL'
    )),
    structure_id    NUMBER(19),
    actif           NUMBER(1)     NOT NULL DEFAULT 1 CHECK (actif IN (0,1)),
    date_creation   TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    date_mise_a_jour TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_user_structure FOREIGN KEY (structure_id) REFERENCES structure_organisationnelle (id) ON DELETE SET NULL
);

CREATE OR REPLACE TRIGGER trg_user_update
BEFORE UPDATE ON utilisateur
FOR EACH ROW
BEGIN
  :NEW.date_mise_a_jour := CURRENT_TIMESTAMP;
END;
/

-- =============================================================================
-- 3. INTERIM_DELEGATION (Délégations temporaires d'intérim)
-- =============================================================================
BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE interim_delegation CASCADE CONSTRAINTS';
EXCEPTION
  WHEN OTHERS THEN NULL;
END;
/

CREATE TABLE interim_delegation (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulaire_id    NUMBER(19) NOT NULL,
    interimaire_id  NUMBER(19) NOT NULL,
    structure_id    NUMBER(19) NOT NULL,
    niveau_delegue  VARCHAR2(20) NOT NULL CHECK (niveau_delegue IN ('DIRECTION','DIVISION','SERVICE','SECTION')),
    date_debut      DATE       NOT NULL,
    date_fin        DATE       NOT NULL,
    actif           NUMBER(1)  NOT NULL DEFAULT 1 CHECK (actif IN (0,1)),
    motif           VARCHAR2(255),
    date_creation   TIMESTAMP  DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_interim_titulaire  FOREIGN KEY (titulaire_id)   REFERENCES utilisateur (id) ON DELETE CASCADE,
    CONSTRAINT fk_interim_interimaire FOREIGN KEY (interimaire_id) REFERENCES utilisateur (id) ON DELETE CASCADE,
    CONSTRAINT fk_interim_struct     FOREIGN KEY (structure_id)    REFERENCES structure_organisationnelle (id) ON DELETE CASCADE
);

-- =============================================================================
-- 4. PROJET (Enrichi avec createur, structure, indicateurs d'activité)
-- =============================================================================
BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE projet CASCADE CONSTRAINTS';
EXCEPTION
  WHEN OTHERS THEN NULL;
END;
/

CREATE TABLE projet (
    id                    NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                  VARCHAR2(50)  NOT NULL UNIQUE,
    intitule              VARCHAR2(255) NOT NULL,
    description           CLOB,
    type_projet           VARCHAR2(50)  NOT NULL DEFAULT 'PLURIANNUEL' CHECK (type_projet IN ('NOUVEAU','PLURIANNUEL','ANCIEN')),
    annee_debut           NUMBER(4),
    annee_fin_prevue      NUMBER(4),
    responsable_id        NUMBER(19),
    createur_id           NUMBER(19),
    structure_id          NUMBER(19),
    action_en_cours       NUMBER(1)    NOT NULL DEFAULT 0 CHECK (action_en_cours IN (0,1)),
    date_derniere_action  TIMESTAMP,
    date_creation         TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    date_mise_a_jour      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_projet_responsable FOREIGN KEY (responsable_id) REFERENCES utilisateur (id) ON DELETE SET NULL,
    CONSTRAINT fk_projet_createur    FOREIGN KEY (createur_id)    REFERENCES utilisateur (id) ON DELETE SET NULL,
    CONSTRAINT fk_projet_structure   FOREIGN KEY (structure_id)   REFERENCES structure_organisationnelle (id) ON DELETE SET NULL
);

CREATE OR REPLACE TRIGGER trg_projet_update
BEFORE UPDATE ON projet
FOR EACH ROW
BEGIN
  :NEW.date_mise_a_jour := CURRENT_TIMESTAMP;
END;
/

-- =============================================================================
-- 5. BILAN_ANNUEL (Enrichi avec situation_details, perspectives_annee_suivante)
-- =============================================================================
BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE bilan_annuel CASCADE CONSTRAINTS';
EXCEPTION
  WHEN OTHERS THEN NULL;
END;
/

CREATE TABLE bilan_annuel (
    id                       NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    projet_id                NUMBER(19) NOT NULL,
    annee                    NUMBER(4)  NOT NULL,
    situation_projet         VARCHAR2(50) NOT NULL CHECK (situation_projet IN ('EN_BONNE_VOIE','SOUS_VIGILANCE','CRITIQUE','TERMINE','SUSPENDU')),
    actions_annee_en_cours   CLOB,
    situation_details        CLOB,
    fonctionnalites_principales CLOB,
    perspectives_annee_suivante CLOB,
    commentaires             CLOB,
    inclus_rapport_annuel    NUMBER(1)  NOT NULL DEFAULT 1 CHECK (inclus_rapport_annuel IN (0,1)),
    date_evaluation          TIMESTAMP  DEFAULT CURRENT_TIMESTAMP,
    date_mise_a_jour         TIMESTAMP  DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_bilan_projet FOREIGN KEY (projet_id) REFERENCES projet (id) ON DELETE CASCADE,
    CONSTRAINT uk_projet_annee UNIQUE (projet_id, annee)
);

CREATE OR REPLACE TRIGGER trg_bilan_update
BEFORE UPDATE ON bilan_annuel
FOR EACH ROW
BEGIN
  :NEW.date_mise_a_jour := CURRENT_TIMESTAMP;
END;
/

-- =============================================================================
-- 6. FONCTIONNALITE (Fonctionnalités avec statut individuel)
-- =============================================================================
BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE fonctionnalite CASCADE CONSTRAINTS';
EXCEPTION
  WHEN OTHERS THEN NULL;
END;
/

CREATE TABLE fonctionnalite (
    id                  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    projet_id           NUMBER(19) NOT NULL,
    bilan_annuel_id     NUMBER(19),
    code                VARCHAR2(50),
    intitule            VARCHAR2(255) NOT NULL,
    description         CLOB,
    statut              VARCHAR2(50)  NOT NULL DEFAULT 'A_FAIRE' CHECK (statut IN ('A_FAIRE','EN_COURS','EN_RECETTE','TERMINE','BLOQUE','ANNULE')),
    est_principale      NUMBER(1)     NOT NULL DEFAULT 0 CHECK (est_principale IN (0,1)),
    priorite            VARCHAR2(30)  DEFAULT 'MOYENNE' CHECK (priorite IN ('BASSE','MOYENNE','HAUTE','CRITIQUE')),
    date_creation       TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    date_mise_a_jour    TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_fonct_projet FOREIGN KEY (projet_id)       REFERENCES projet (id) ON DELETE CASCADE,
    CONSTRAINT fk_fonct_bilan  FOREIGN KEY (bilan_annuel_id) REFERENCES bilan_annuel (id) ON DELETE SET NULL
);

CREATE OR REPLACE TRIGGER trg_fonct_update
BEFORE UPDATE ON fonctionnalite
FOR EACH ROW
BEGIN
  :NEW.date_mise_a_jour := CURRENT_TIMESTAMP;
END;
/

